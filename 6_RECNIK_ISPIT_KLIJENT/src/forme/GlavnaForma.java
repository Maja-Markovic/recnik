    private void jButtonLogoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLogoutActionPerformed

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.LOGOUT, ulogovani);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspeh = (boolean) so.getOdgovor();

        if (uspeh) {
            LoginForma lf = new LoginForma();
            lf.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(null, "GRESKA");
        }

    }//GEN-LAST:event_jButtonLogoutActionPerformed

    private void jButtonPretragaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPretragaActionPerformed
        String rec = jTextFieldRec.getText();

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.PRETRAGA, rec);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        Rec r = (Rec) so.getOdgovor();

        if (r == null) {
            JOptionPane.showMessageDialog(null, "NE POSTOJI REC");
            jButtonUnesi.setVisible(true);
            jTextArea1.setEditable(true);
        } else {
            String rezultat = "";
            for (Prevod prevod : r.getPrevodi()) {
                rezultat += prevod.getEngleskaRec();
                rezultat += ";";
            }
            jTextArea1.setText(rezultat);

        }


    }//GEN-LAST:event_jButtonPretragaActionPerformed

    private void jButtonUnesiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUnesiActionPerformed
        String srpRec = jTextFieldRec.getText();
        String prevodi = jTextArea1.getText();
        String[] nizPrevoda = prevodi.split(";");

        Rec r = new Rec();
        r.setSrpskaRec(srpRec);
        List<Prevod> lista = new ArrayList<>();
        for (String el : nizPrevoda) {
            Prevod p = new Prevod();
            p.setEngleskaRec(el);
            p.setSrpskaRec(r);
            lista.add(p);
        }
        r.setPrevodi(lista);

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.UNESI, r);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspeh = (boolean) so.getOdgovor();

        if (uspeh) {
            JOptionPane.showMessageDialog(null, "USPEH");
            popuniTabeluRecnik();
            jTextArea1.setEditable(false);
            jButtonUnesi.setVisible(false);
        } else {
            JOptionPane.showMessageDialog(null, "GRESKA");
        }


    }//GEN-LAST:event_jButtonUnesiActionPerformed



    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        String email = jTextFieldEmail.getText();
        String lozinka = String.valueOf(jPasswordFieldLozinka.getPassword());
        
        Korisnik k = new Korisnik();
        k.setEmail(email);
        k.setLozinka(lozinka);
        
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.LOGIN, k);
        Komunikacija.getInstance().posaljiZahtev(kz);
        
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        Korisnik korisnik = (Korisnik) so.getOdgovor();
        
        if(korisnik == null){
            JOptionPane.showMessageDialog(null, "GRESKA");
        }else{
            GlavnaForma gf = new GlavnaForma(korisnik);
            gf.setVisible(true);
            this.dispose();
        }
        
        
        
    }//GEN-LAST:event_jButtonLoginActionPerformed

